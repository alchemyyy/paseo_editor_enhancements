function goEnvironment() {
  const gopath = path.join(cache, "gopath");
  return {
    ...process.env,
    GOOS: "js",
    GOARCH: "wasm",
    CGO_ENABLED: "0",
    GOTOOLCHAIN: "local",
    GOFLAGS: "-mod=mod",
    GOPATH: gopath,
    GOMODCACHE: path.join(gopath, "pkg", "mod"),
    GOCACHE: path.join(cache, "gocache"),
    GOTELEMETRY: "off",
  };
}

/** gh-gfm-preview's renderer as WebAssembly, Go's loader for it, and the licenses of what it contains */
function buildWasm(go, checkout) {
  const env = goEnvironment();
  const output = path.join(cache, "gfm.wasm");
  run(go, ["build", "-trimpath", "-ldflags=-s -w", "-o", output, "./cmd/paseo-wasm"], { cwd: checkout, env });
  const goroot = run(go, ["env", "GOROOT"], { env }).trim();
  const loader = [path.join(goroot, "lib", "wasm", "wasm_exec.js"), path.join(goroot, "misc", "wasm", "wasm_exec.js")].find(existsSync);
  if (!loader) throw new Error(`No wasm_exec.js in ${goroot}`);

  // One JSON object per package, concatenated
  const listing = run(go, ["list", "-deps", "-json", "./cmd/paseo-wasm"], { cwd: checkout, env });
  const modules = new Map();
  for (const chunk of listing.split(/\n(?=\{)/)) {
    const module = JSON.parse(chunk).Module;
    if (module && !module.Main && module.Dir) modules.set(module.Path, module);
  }
  const notices = [
    `gh-gfm-preview@${GH_GFM_PREVIEW.commit} (github.com/${GH_GFM_PREVIEW.repository})\n\n${licenseText(checkout)}`,
    `Go ${run(go, ["env", "GOVERSION"], { env }).trim().replace(/^go/, "")} (runtime, standard library, wasm_exec.js)\n\n${licenseText(goroot)}`,
    ...[...modules.values()]
      .sort((left, right) => left.Path.localeCompare(right.Path))
      .map((module) => `${module.Path}@${module.Version}\n\n${licenseText(module.Dir)}`),
  ];
  return { wasm: readFileSync(output), loader: readFileSync(loader), notices };
}

/** Renders a sample with the built engine in Node, so a broken build never ships */
async function checkWasm(wasm, loader) {
  // wasm_exec.js defines globalThis.Go, with Node polyfills where it needs them
  vm.runInThisContext(loader.toString("utf8"));
  const go = new globalThis.Go();
  const { instance } = await WebAssembly.instantiate(wasm, go.importObject);
  void go.run(instance);
  const sample = "# Title\n\nText with :rocket:\n\n```js\nlet a = 1\n```\n\n```mermaid\ngraph TD\n```\n\n> [!NOTE]\n> Note\n";
  const result = globalThis.paseoGfmRender(sample, 2);
  if (result.error) throw new Error(`gfm.wasm: ${result.error}`);
  const expectations = [
    [/<h1 [^>]*data-source-line="3"/, "source line of the heading"],
    [/class="chroma"/, "chroma highlighting"],
    [/<code class="language-mermaid">/, "Mermaid code kept for the page"],
    [/markdown-alert-note/, "GitHub alerts"],
    [/&#x1f680;|\u{1F680}/u, "emoji shortcodes"],
  ];
  for (const [pattern, what] of expectations) {
    if (!pattern.test(result.html)) throw new Error(`gfm.wasm lacks ${what}:\n${result.html}`);
  }
}

/** Every MathJax TeX extension, which its autoloader asks for as macros need them */
function mathjaxExtensions(directory) {
  const extensions = path.join(directory, "es5", "input", "tex", "extensions");
  const files = {};
  for (const name of readdirSync(extensions).sort()) {
    if (name.endsWith(".js")) files[name] = readFileSync(path.join(extensions, name), "utf8");
  }
  return Buffer.from(JSON.stringify(files));
}

