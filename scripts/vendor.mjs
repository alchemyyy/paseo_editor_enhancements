async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, ...options });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed (${result.status}):\n${result.stdout}${result.stderr}`);
  }
  return result.stdout;
}

/** Unpacks a .zip or .tar.gz archive with the system tar (bsdtar on Windows and macOS reads zip) */
function extract(archive, destination) {
  mkdirSync(destination, { recursive: true });
  run("tar", ["-xf", archive, "-C", destination]);
}

function goVersionOf(go) {
  const result = spawnSync(go, ["env", "GOVERSION"], { encoding: "utf8" });
  const match = result.status === 0 ? /^go(\d+)\.(\d+)/.exec(result.stdout.trim()) : null;
  return match ? [Number(match[1]), Number(match[2])] : null;
}

/** A Go 1.25+ toolchain: GO, the `go` on PATH, or one downloaded into the cache */
async function ensureGo() {
  for (const candidate of [process.env.GO, "go"].filter(Boolean)) {
    const version = goVersionOf(candidate);
    if (version && (version[0] > MINIMUM_GO[0] || (version[0] === MINIMUM_GO[0] && version[1] >= MINIMUM_GO[1]))) {
      return candidate;
    }
  }
  const os = { win32: "windows", darwin: "darwin", linux: "linux" }[process.platform];
  const arch = { x64: "amd64", arm64: "arm64" }[process.arch];
  if (!os || !arch) throw new Error(`No Go download for ${process.platform}/${process.arch}; set GO to a Go 1.25+ binary`);
  const directory = path.join(cache, `go${GO_VERSION}`);
  const binary = path.join(directory, "go", "bin", os === "windows" ? "go.exe" : "go");
  if (existsSync(binary)) return binary;
  const filename = `go${GO_VERSION}.${os}-${arch}.${os === "windows" ? "zip" : "tar.gz"}`;
  const releases = JSON.parse((await download("https://go.dev/dl/?mode=json&include=all")).toString("utf8"));
  const expected = releases.flatMap((release) => release.files).find((file) => file.filename === filename)?.sha256;
  if (!expected) throw new Error(`go.dev lists no ${filename}`);
  console.log(`Downloading ${filename}`);
  const bytes = await download(`https://go.dev/dl/${filename}`);
  const actual = createHash("sha256").update(bytes).digest("hex");
  if (actual !== expected) throw new Error(`${filename}: sha256 ${actual}, expected ${expected}`);
  mkdirSync(cache, { recursive: true });
  const archive = path.join(cache, filename);
  writeFileSync(archive, bytes);
  rmSync(directory, { recursive: true, force: true });
  extract(archive, directory);
  rmSync(archive);
  return binary;
}

/** A fresh checkout of gh-gfm-preview at the pinned commit with vendor-src/gfm/ added */
async function ghGfmPreviewCheckout() {
  const tarball = path.join(cache, `gh-gfm-preview-${GH_GFM_PREVIEW.commit}.tar.gz`);
  if (!existsSync(tarball)) {
    mkdirSync(cache, { recursive: true });
    const url = `https://codeload.github.com/${GH_GFM_PREVIEW.repository}/tar.gz/${GH_GFM_PREVIEW.commit}`;
    writeFileSync(tarball, await download(url));
  }
  const checkout = path.join(cache, `gh-gfm-preview-${GH_GFM_PREVIEW.commit}`);
  rmSync(checkout, { recursive: true, force: true });
  extract(tarball, cache);
  if (!existsSync(path.join(checkout, "go.mod"))) throw new Error(`${tarball} did not unpack to ${checkout}`);

  // ToHTML takes the parser options vendor-src/gfm/paseo.go declares, for the source-line marks
  const appFile = path.join(checkout, "internal", "app", "app.go");
  const app = readFileSync(appFile, "utf8");
  const original = "goldmark.WithParserOptions(parser.WithAutoHeadingID()),";
  const patched = "goldmark.WithParserOptions(append([]parser.Option{parser.WithAutoHeadingID()}, ExtraParserOptions...)...),";
  if (app.split(original).length !== 2) throw new Error(`internal/app/app.go no longer builds its parser options as expected`);
  writeFileSync(appFile, app.replace(original, patched));
  copyFileSync(path.join(root, "vendor-src", "gfm", "paseo.go"), path.join(checkout, "internal", "app", "paseo.go"));
  mkdirSync(path.join(checkout, "cmd", "paseo-wasm"), { recursive: true });
  copyFileSync(path.join(root, "vendor-src", "gfm", "main.go"), path.join(checkout, "cmd", "paseo-wasm", "main.go"));
  return checkout;
}

