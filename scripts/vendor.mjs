// Builds what the plugin ships instead of node_modules. Paseo compiles the plugin from source with
// esbuild and supplies only its SDK, React, React Native, React Query, and zod; anything else must
// ship inside client/ or server/.
//
//   client/vendor/markdown.js            vendor-src/markdown.ts with DOMPurify and yaml; its
//                                        declarations are the hand-written markdown.d.ts beside it
//   client/vendor/github-markdown.ts     github-markdown-css split into its color-free rules and its
//                                        light and dark color variables, so palettes can swap colors
//   client/vendor/gfm-styles.ts          gh-gfm-preview's chroma syntax colors (GitHub light/dark),
//                                        and the same rules reading palette variables
//   server/vendor/engine-assets.json     the GitHub engine, gzipped and base64-encoded: gh-gfm-preview's
//                                        renderer built for WebAssembly with Go's wasm_exec.js, and the
//                                        Mermaid, MathJax (SVG output), Leaflet, and TopoJSON code it
//                                        runs in the page; the client fetches each on first use
//   {client,server}/vendor/THIRD_PARTY_LICENSES.txt
//
// The GitHub engine is built from gh-gfm-preview at a pinned commit (downloaded into
// node_modules/.cache) with vendor-src/gfm/ added to it. It needs Go 1.25 or later: the `go` on
// PATH, or GO=<path to go>, or else this script downloads Go into node_modules/.cache.
//
// Run after changing vendor-src/ or the pinned versions: npm run vendor
import { build } from "esbuild";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, copyFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import { gzipSync } from "node:zlib";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "package.json"));
const clientVendor = path.join(root, "client", "vendor");
const serverVendor = path.join(root, "server", "vendor");
const cache = path.join(root, "node_modules", ".cache", "editor-enhancements");
const GENERATED = "// Generated by scripts/vendor.mjs; do not edit.\n";
const RULE = `\n\n${"-".repeat(72)}\n\n`;

/** gh-gfm-preview, the GitHub engine (MIT, Thiago Kenji Okada) */
const GH_GFM_PREVIEW = { repository: "thiagokokada/gh-gfm-preview", commit: "c127e30b4ad4dbc1f63b52bed7a677013e5349c6" };
/** Downloaded when no Go 1.25+ is available */
const GO_VERSION = "1.27.3";
const MINIMUM_GO = [1, 25];
/** Libraries gh-gfm-preview vendors for its page (internal/server/static/generated), and their licenses */
const PAGE_LIBRARIES = [
  { name: "mermaid", version: "11.3.0", file: "mermaid.min.js", asset: "mermaid.js", license: "mermaid-js/mermaid/mermaid%4011.3.0/LICENSE" },
  { name: "leaflet", version: "1.9.4", file: "leaflet.js", asset: "leaflet.js", license: "Leaflet/Leaflet/v1.9.4/LICENSE" },
  { name: "leaflet (stylesheet)", version: "1.9.4", file: "leaflet.css", asset: "leaflet.css", license: null },
  {
    name: "topojson-client",
    version: "3.1.0",
    file: "topojson-client.min.js",
    asset: "topojson.js",
    license: "topojson/topojson-client/v3.1.0/LICENSE",
  },
];

