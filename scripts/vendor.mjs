/** The package directory and name that own a bundled file */
function owningPackage(file) {
  const parts = path.resolve(root, file).split(path.sep);
  const index = parts.lastIndexOf("node_modules");
  if (index === -1) return null;
  const size = parts[index + 1].startsWith("@") ? 2 : 1;
  return {
    name: parts.slice(index + 1, index + 1 + size).join("/"),
    directory: parts.slice(0, index + 1 + size).join(path.sep),
  };
}

function licenseText(directory) {
  const file = readdirSync(directory).find((name) => /^(licen[cs]e|copying|unlicense)([.-]|$)/i.test(name));
  if (!file) throw new Error(`No license file in ${directory}`);
  return readFileSync(path.join(directory, file), "utf8").trim();
}

function packageVersion(directory) {
  return JSON.parse(readFileSync(path.join(directory, "package.json"), "utf8")).version;
}

function packageDirectory(name) {
  return path.dirname(require.resolve(`${name}/package.json`));
}

/** client/vendor/markdown.js; returns the packages bundled into it */
async function vendorClientBundle() {
  const result = await build({
    entryPoints: [path.join(root, "vendor-src", "markdown.ts")],
    bundle: true,
    format: "cjs",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
    metafile: true,
    outfile: path.join(clientVendor, "markdown.js"),
    banner: { js: GENERATED },
  });
  const packages = new Map();
  for (const input of Object.keys(result.metafile.inputs)) {
    const owner = owningPackage(input);
    if (owner) packages.set(owner.name, owner.directory);
  }
  return packages;
}

/** `{ "--name": "value" }` from the declarations of one CSS block body */
function variables(block) {
  const entries = [...block.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]);
  return Object.fromEntries(entries);
}

/**
 * github-markdown.css opens with a block of size and font variables, then one block of color
 * variables per `prefers-color-scheme`; every rule after them reads colors only from variables.
 */
function vendorGithubCss() {
  const directory = packageDirectory("github-markdown-css");
  const css = readFileSync(path.join(directory, "github-markdown.css"), "utf8");
  const scheme = (name) => {
    const match = new RegExp(
      `@media \\(prefers-color-scheme: ${name}\\) \\{\\s*\\.markdown-body, \\[data-theme="${name}"\\] \\{([\\s\\S]*?)\\n  \\}\\n\\}\\n`,
    ).exec(css);
    if (!match) throw new Error(`github-markdown.css has no ${name} color block`);
    return match;
  };
  const dark = scheme("dark");
  const light = scheme("light");
  const base = /^\.markdown-body \{([\s\S]*?)\n\}\n/.exec(css);
  if (!base) throw new Error("github-markdown.css has no leading variable block");
  const rules = css.slice(Math.max(dark.index + dark[0].length, light.index + light[0].length)).trim();
  if (/#[0-9a-f]{3,8}\b/i.test(rules)) throw new Error("github-markdown.css rules hold literal colors");

  const source = [
    GENERATED,
    `// github-markdown-css@${packageVersion(directory)} (MIT, Sindre Sorhus); see THIRD_PARTY_LICENSES.txt.\n\n`,
    "/** Size and font variables every GitHub color scheme shares */\n",
    `export const GITHUB_BASE_VARIABLES: Readonly<Record<string, string>> = ${JSON.stringify(variables(base[1]), null, 2)};\n\n`,
    "/** GitHub's light color variables */\n",
    `export const GITHUB_LIGHT_VARIABLES: Readonly<Record<string, string>> = ${JSON.stringify(variables(light[1]), null, 2)};\n\n`,
    "/** GitHub's dark color variables */\n",
    `export const GITHUB_DARK_VARIABLES: Readonly<Record<string, string>> = ${JSON.stringify(variables(dark[1]), null, 2)};\n\n`,
    "/** Every `.markdown-body` rule; colors come only from the variables above */\n",
    `export const GITHUB_MARKDOWN_RULES = ${JSON.stringify(rules)};\n`,
  ].join("");
  writeFileSync(path.join(clientVendor, "github-markdown.ts"), source);
  return directory;
}

