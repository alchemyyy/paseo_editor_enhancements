/**
 * What each color of chroma's GitHub light style means, as the variable a palette sets for it.
 * A color missing here fails the build, so a new gh-gfm-preview cannot slip in unmapped colors.
 */
const CHROMA_COLOR_VARIABLES = {
  "#f6f8fa": "--bgColor-muted",
  "#cf222e": "--color-prettylights-syntax-keyword",
  "#990000": "--fgColor-danger",
  "#0550ae": "--color-prettylights-syntax-constant",
  "#6639ba": "--color-prettylights-syntax-entity",
  "#953800": "--color-prettylights-syntax-variable",
  "#0a3069": "--color-prettylights-syntax-string",
  "#032f62": "--color-prettylights-syntax-string",
  "#57606a": "--color-prettylights-syntax-comment",
  "#6a737d": "--color-prettylights-syntax-comment",
  "#1f2328": "--fgColor-default",
  "#24292e": "--fgColor-default",
  "#82071e": "--color-prettylights-syntax-markup-deleted-text",
  "#ffebe9": "--color-prettylights-syntax-markup-deleted-bg",
  "#116329": "--color-prettylights-syntax-markup-inserted-text",
  "#dafbe1": "--color-prettylights-syntax-markup-inserted-bg",
  "#7f7f7f": "--fgColor-muted",
  "#dedede": "--bgColor-neutral-muted",
  "#ffffff": "--bgColor-default",
};

/** chroma's GitHub light rules with each color replaced by the palette variable that means it */
function paletteChroma(light) {
  return light.replace(/#[0-9a-f]{6}\b/gi, (color) => {
    const variable = CHROMA_COLOR_VARIABLES[color.toLowerCase()];
    if (!variable) throw new Error(`chroma-github-light.css: no palette variable for ${color}`);
    return `var(${variable})`;
  });
}

function vendorGfmStyles(checkout) {
  const generated = path.join(checkout, "internal", "server", "static", "generated");
  const light = readFileSync(path.join(generated, "chroma-github-light.css"), "utf8").trim();
  const dark = readFileSync(path.join(generated, "chroma-github-dark.css"), "utf8").trim();
  const source = [
    GENERATED,
    `// From gh-gfm-preview@${GH_GFM_PREVIEW.commit} (MIT); see THIRD_PARTY_LICENSES.txt.\n\n`,
    "/** gh-gfm-preview's code colors: chroma's GitHub style */\n",
    `export const CHROMA_GITHUB_LIGHT = ${JSON.stringify(light)};\n\n`,
    "/** gh-gfm-preview's code colors: chroma's GitHub dark style */\n",
    `export const CHROMA_GITHUB_DARK = ${JSON.stringify(dark)};\n\n`,
    "/** The GitHub style's rules with its colors read from palette variables */\n",
    `export const CHROMA_PALETTE = ${JSON.stringify(paletteChroma(light))};\n`,
  ].join("");
  writeFileSync(path.join(clientVendor, "gfm-styles.ts"), source);
}

// ---------------------------------------------------------------------------------------------

function writeLicenses(directory, title, notices) {
  writeFileSync(path.join(directory, "THIRD_PARTY_LICENSES.txt"), `${title}\n\n${notices.join(RULE)}\n`);
}

mkdirSync(clientVendor, { recursive: true });
mkdirSync(serverVendor, { recursive: true });

const clientPackages = await vendorClientBundle();
clientPackages.set("github-markdown-css", vendorGithubCss());
const checkout = await ghGfmPreviewCheckout();
vendorGfmStyles(checkout);
writeLicenses(clientVendor, "Third-party code in client/vendor/", [
  ...[...clientPackages]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, directory]) => `${name}@${packageVersion(directory)}\n\n${licenseText(directory)}`),
  `gh-gfm-preview@${GH_GFM_PREVIEW.commit} (gfm-styles.ts)\n\n${licenseText(checkout)}`,
]);

const go = await ensureGo();
const { wasm, loader, notices } = buildWasm(go, checkout);
await checkWasm(wasm, loader);
const generated = path.join(checkout, "internal", "server", "static", "generated");
const mathjax = packageDirectory("mathjax");
const assets = {
  "gfm.wasm": wasm,
  "wasm_exec.js": loader,
  "mathjax.js": readFileSync(path.join(mathjax, "es5", "tex-mml-svg.js")),
  "mathjax-extensions.json": mathjaxExtensions(mathjax),
  ...Object.fromEntries(PAGE_LIBRARIES.map((library) => [library.asset, readFileSync(path.join(generated, library.file))])),
};
const encoded = Object.fromEntries(
  Object.entries(assets).map(([name, bytes]) => [name, gzipSync(bytes, { level: 9 }).toString("base64")]),
);
writeFileSync(path.join(serverVendor, "engine-assets.json"), `${JSON.stringify(encoded)}\n`);

const libraryNotices = [];
for (const library of PAGE_LIBRARIES) {
  if (!library.license) continue;
  const text = (await download(`https://raw.githubusercontent.com/${library.license}`)).toString("utf8").trim();
  libraryNotices.push(`${library.name}@${library.version}\n\n${text}`);
}
writeLicenses(serverVendor, "Third-party code in server/vendor/engine-assets.json", [
  ...notices,
  `mathjax@${packageVersion(mathjax)}\n\n${licenseText(mathjax)}`,
  ...libraryNotices,
]);

for (const [name, bytes] of Object.entries(assets)) {
  console.log(`${name.padEnd(24)} ${(bytes.length / 1024).toFixed(0).padStart(6)} KB -> ${(encoded[name].length / 1024).toFixed(0).padStart(5)} KB`);
}
// The Go runtime started by checkWasm stays parked on its event queue
process.exit(0);
